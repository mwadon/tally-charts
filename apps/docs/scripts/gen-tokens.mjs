// Generates tokens.generated.ts from the library theme (packages/tally-charts/src/theme/theme.css),
// see CLAUDE.md, `pnpm --filter docs gen`. Plain Node, no dist, no network.
//
// The theme has no token list in code, only CSS, so the docs read the declarations: `theme`
// tokens are declared for light and dark, `shared` tokens once for both. Private --_ch-* variables
// are not part of the public API and are skipped.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const themeFile = path.resolve(appDir, '../../packages/tally-charts/src/theme/theme.css')

const TONES = ['accent', 'accent-soft', 'loss', 'warn', 'gain', 'neutral']
const VIVID_TONES = ['warn', 'gain', 'neutral']
const HEX = /^#[0-9a-f]{6}$/i

class ThemeError extends Error {
  constructor(problem) {
    super(`theme.css: ${problem}`)
  }
}

/** The text of the block whose body opens at `open` (the index of `{`), without the braces. */
function blockBody(css, open) {
  let depth = 0
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) return css.slice(open + 1, i)
  }
  throw new ThemeError('unbalanced braces')
}

/** `--name: value` declarations of a block body, without those of nested blocks. */
function declarations(body) {
  let top = ''
  let depth = 0
  for (const ch of body) {
    if (ch === '{') depth++
    else if (ch === '}') depth--
    else if (depth === 0) top += ch
  }
  const out = new Map()
  for (const m of top.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    out.set(m[1], m[2].replace(/\s+/g, ' ').trim())
  }
  return out
}

/** Declarations of the block that follows the first match of `header`. */
function blockAfter(css, header, what) {
  const match = header.exec(css)
  if (!match) throw new ThemeError(`no ${what} block`)
  return declarations(blockBody(css, match.index + match[0].length - 1))
}

const publicOnly = (decls) => new Map([...decls].filter(([name]) => name.startsWith('--ch-')))

/** Tokens and palettes of a theme stylesheet. Throws a `theme.css: problem` error on a bad shape. */
export function collectTokens(source) {
  const css = source.replace(/\/\*[\s\S]*?\*\//g, '')
  const light = publicOnly(blockAfter(css, /^:root,\s*\[data-ch-theme="light"\]\s*\{/m, 'light'))
  const dark = publicOnly(blockAfter(css, /^\[data-ch-theme="dark"\]\s*\{/m, 'dark'))
  const shared = publicOnly(blockAfter(css, /^:root\s*\{/m, 'theme-independent'))

  const tokens = []
  for (const [name, value] of light) {
    const darkValue = dark.get(name)
    if (darkValue === undefined) throw new ThemeError(`${name} has a light value but no dark value`)
    tokens.push({ name, group: 'theme', light: value, dark: darkValue })
  }
  for (const name of dark.keys()) {
    if (!light.has(name)) throw new ThemeError(`${name} has a dark value but no light value`)
  }
  for (const [name, value] of shared) {
    if (light.has(name)) throw new ThemeError(`${name} is declared as a theme and a shared token`)
    tokens.push({ name, group: 'shared', light: value, dark: value })
  }

  const tone = (map, name, theme) => {
    const value = map.get(`--ch-${name}`)
    if (value === undefined || !HEX.test(value)) {
      throw new ThemeError(`--ch-${name} (${theme}) is not a #rrggbb color`)
    }
    return value
  }
  const tones = (map, theme, names = TONES) =>
    Object.fromEntries(names.map((name) => [name, tone(map, name, theme)]))

  const vividMatch = /\[data-ch-palette="vivid"\][^{}]*\{/.exec(css)
  if (!vividMatch) throw new ThemeError('no vivid palette block')
  const vivid = declarations(blockBody(css, vividMatch.index + vividMatch[0].length - 1))

  const defaultLight = tones(light, 'light')
  const palettes = {
    default: {
      light: defaultLight,
      dark: tones(dark, 'dark'),
      surface: { light: tone(light, 'surface', 'light'), dark: tone(dark, 'surface', 'dark') },
    },
    vivid: {
      light: { ...defaultLight, ...tones(vivid, 'vivid', VIVID_TONES) },
      surface: { light: tone(light, 'surface', 'light') },
    },
  }
  return { tokens, palettes }
}

/** The text of tokens.generated.ts. Deterministic. */
export function renderTokens({ tokens, palettes }) {
  const json = (value) => JSON.stringify(value, null, 2)
  return `// Generated by scripts/gen-tokens.mjs from packages/tally-charts/src/theme/theme.css, do not edit.
// Run \`pnpm --filter docs gen\`; dev, build, test and typecheck run it first.

export const TOKEN_GROUPS = ['theme', 'shared'] as const

export type TokenGroup = (typeof TOKEN_GROUPS)[number]

export interface Token {
  name: \`--ch-\${string}\`
  /** \`theme\` tokens differ per theme; \`shared\` tokens have the same value in both (light === dark). */
  group: TokenGroup
  light: string
  dark: string
}

export type PaletteTone = ${TONES.map((t) => `'${t}'`).join(' | ')}

export interface Palette {
  light: Record<PaletteTone, string>
  /** Absent when the palette is light only. */
  dark?: Record<PaletteTone, string>
  surface: { light: string; dark?: string }
}

export const TOKENS: readonly Token[] = ${json(tokens)}

export const PALETTES: { default: Palette; vivid: Palette } = ${json(palettes)}
`
}

/** Writes the tokens next to the app. Returns whether the file changed. */
export function generate(root = appDir, cssFile = themeFile) {
  const output = path.join(root, 'tokens.generated.ts')
  const next = renderTokens(collectTokens(readFileSync(cssFile, 'utf8')))
  if (existsSync(output) && readFileSync(output, 'utf8') === next) return false
  writeFileSync(output, next)
  return true
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const changed = generate()
    console.log(
      changed ? 'gen: wrote tokens.generated.ts' : 'gen: tokens.generated.ts is up to date',
    )
  } catch (error) {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  }
}
